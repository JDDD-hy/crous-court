// Usage: node scripts/verify-venue-preview.mjs <local-origin> [absolute playwright entrypoint]
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { pathToFileURL } from "node:url";
const origin = process.argv[2] || "http://localhost:5174";
if (!["localhost", "127.0.0.1"].includes(new URL(origin).hostname)) throw new Error("Local preview only");
const { chromium } = await import(process.argv[3] ? pathToFileURL(process.argv[3]).href : "playwright");
const browser = await chromium.launch({ channel: "msedge", headless: true });
const outputs = new URL("../.sites-runtime/review-20260915/", import.meta.url);
await mkdir(outputs, { recursive: true });
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, geolocation: { latitude: 48.7128, longitude: 2.2051, accuracy: 200 }, permissions: ["geolocation"], reducedMotion: "reduce" });
  const page = await context.newPage();
  page.on("pageerror", (error) => { errors.push(error.message); console.error("BROWSER ERROR", error.message); });
  page.on("console", (message) => { if (message.type() === "error") console.error("CONSOLE", message.text()); });
  const external = [];
  page.on("request", (request) => { if (!request.url().startsWith(origin) && /^https?:/.test(request.url())) external.push(request.url()); });
  await page.goto(`${origin}/venues`, { waitUntil: "networkidle" });
  await page.getByText("尚未取得位置，当前结果未按距离排序。", { exact: true }).waitFor();
  assert.equal(await page.locator("[data-venue-id]").count(), 0, "No unlocated full-directory dump");
  await page.getByRole("searchbox").fill("escoffier");
  await page.waitForFunction(() => document.querySelectorAll("[data-venue-id]").length === 2);
  assert.equal(await page.locator("[data-venue-id]").count(), 2);
  assert.match(await page.locator("main").innerText(), /官网地址存在疑点/);
  await page.getByRole("button", { name: "查找附近", exact: true }).click();
  await page.getByText("定位精度约", { exact: false }).waitFor();
  await page.getByText("先按搜索匹配程度排序，同等匹配时按距离排序。", { exact: true }).waitFor();
  assert.equal(await page.locator("[data-venue-id]").count(), 2);
  const ru = page.locator('[data-venue-id="ru-escoffier-2"]');
  await ru.getByRole("button", { name: "选择", exact: true }).click();
  await page.getByRole("button", { name: "返回附近 1 km", exact: true }).click();
  assert.equal(await page.locator("[data-venue-id]").count(), 4, "Only four nearby Palaiseau services within 1 km");
  await context.setGeolocation({ latitude: 48.8566, longitude: 2.3522, accuracy: 20 });
  // Deliver the new point directly: Chromium may reuse its permitted 60-second cached fix.
  await page.evaluate(() => { navigator.geolocation.getCurrentPosition = (ok) => ok({ coords: { latitude: 48.8566, longitude: 2.3522, accuracy: 20 } }); });
  await page.getByRole("button", { name: "查找附近", exact: true }).click();
  await page.getByText("1 km 内没有餐厅，请输入名称搜索其他餐厅。", { exact: true }).waitFor();
  assert.equal(await page.locator("[data-venue-id]").count(), 0);
  await page.getByRole("searchbox").fill("Escoffier");
  await page.waitForFunction(() => document.querySelectorAll("[data-venue-id]").length === 2);
  await page.locator('[data-venue-id="cafeteria-escoffier-2"]').getByRole("button", { name: "选择", exact: true }).click();
  await page.getByText("已选择: Cafétéria Escoffier", { exact: true }).waitFor();
  await ru.getByRole("button", { name: "选择", exact: true }).click();
  await page.reload({ waitUntil: "networkidle" });
  await page.getByText("已选择: RU Escoffier", { exact: true }).waitFor();
  await page.getByRole("searchbox").fill("cafet escoffier");
  await page.waitForFunction(() => document.querySelectorAll("[data-venue-id]").length === 1);
  assert.equal(await page.locator("[data-venue-id]").count(), 1);
  await page.getByRole("searchbox").fill("escofier");
  await page.getByText("没有精确匹配，以下是相似名称。", { exact: true }).waitFor();
  assert.equal(await page.locator('[data-approximate="true"]').count(), 2);
  await page.getByRole("searchbox").fill("unmatchable-place");
  await page.getByText("没有匹配的餐厅", { exact: false }).waitFor();
  await page.getByRole("searchbox").fill("Palaiseau");
  await page.screenshot({ path: new URL("venues-zh-desktop.png", outputs).pathname.replace(/^\/(\w:)/, "$1"), fullPage: true });
  await context.addCookies([{ name: "crous-locale", value: "en", url: origin }]);
  await page.reload({ waitUntil: "networkidle" });
  assert.equal(await page.locator("html").getAttribute("lang"), "en");
  await page.getByRole("searchbox").fill("Escoffier");
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await page.screenshot({ path: new URL("venues-en-mobile.png", outputs).pathname.replace(/^\/(\w:)/, "$1"), fullPage: true });
  await page.evaluate(() => { document.documentElement.style.fontSize = "200%"; });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  assert.deepEqual(external, [], "Location/search must not send coordinates to an external service");
  await context.close();

  for (const code of [1, 2, 3]) {
    const deniedContext = await browser.newContext();
    await deniedContext.addInitScript((errorCode) => { navigator.geolocation.getCurrentPosition = (_ok, fail) => fail({ code: errorCode }); }, code);
    const deniedPage = await deniedContext.newPage();
    await deniedPage.goto(`${origin}/venues`, { waitUntil: "networkidle" });
    await deniedPage.getByRole("button", { name: "查找附近", exact: true }).click();
    await deniedPage.getByRole("alert").waitFor();
    await deniedPage.getByText("尚未取得位置，当前结果未按距离排序。", { exact: true }).waitFor();
    await deniedPage.getByRole("searchbox").fill("Escoffier");
    await deniedPage.waitForFunction(() => document.querySelectorAll("[data-venue-id]").length === 2);
    assert.equal(await deniedPage.locator("[data-venue-id]").count(), 2);
    await deniedContext.close();
  }
  const cancelledContext = await browser.newContext();
  await cancelledContext.addInitScript(() => {
    navigator.geolocation.getCurrentPosition = (ok) => { window.deliverTestLocation = () => ok({ coords: { latitude: 48.7128, longitude: 2.2051, accuracy: 20 } }); };
    Storage.prototype.setItem = () => { throw new Error("Storage disabled for QA"); };
  });
  const cancelledPage = await cancelledContext.newPage();
  await cancelledPage.goto(`${origin}/venues`, { waitUntil: "networkidle" });
  await cancelledPage.getByRole("button", { name: "查找附近", exact: true }).click();
  await cancelledPage.getByRole("button", { name: "取消定位", exact: true }).click();
  await cancelledPage.evaluate(() => window.deliverTestLocation());
  assert.equal(await cancelledPage.getByText("定位精度约", { exact: false }).count(), 0);
  await cancelledPage.getByRole("searchbox").fill("RU Escoffier");
  await cancelledPage.waitForFunction(() => document.querySelectorAll("[data-venue-id]").length === 1);
  await cancelledPage.getByRole("button", { name: "选择", exact: true }).click();
  await cancelledPage.getByText("当前浏览器无法保存偏好", { exact: false }).waitFor();
  await cancelledContext.close();
  assert.deepEqual(errors, []);
  console.log("PASS: official service disambiguation, typo/no-match, location accuracy/denied/unavailable/timeout, persistence, English, mobile/200% layout, no external location requests.");
} finally { await browser.close(); }
