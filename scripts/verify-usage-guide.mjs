// Run against a local preview; no login, email or database writes.
import assert from "node:assert/strict";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");

const origin = process.env.PREVIEW_URL || "http://127.0.0.1:8798";
assert.ok(["localhost", "127.0.0.1"].includes(new URL(origin).hostname));
const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 1000 }, reducedMotion: "reduce" });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(origin);
  const guide = page.getByRole("dialog");
  await guide.waitFor();
  assert.match(await guide.innerText(), /使用以上附近餐厅/);
  await page.waitForTimeout(350);
  await page.screenshot({ path: "work/usage-guide-desktop.png" });
  await guide.getByRole("button", { name: "去选案发地点" }).click();
  await guide.waitFor({ state: "hidden" });
  assert.equal(await page.locator("[data-venue-menu]").evaluate(el => el.open), true);
  assert.equal(await page.locator("[data-venue-menu] summary").evaluate(el => el === document.activeElement), true);
  await page.reload();
  await page.getByRole("button", { name: "使用说明", exact: true }).click();
  await guide.waitFor();
  await page.keyboard.press("Escape");
  await guide.waitFor({ state: "hidden" });
  await page.reload();
  await page.waitForTimeout(500);
  assert.equal(await guide.count(), 0, "dismissal survives reload");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "使用说明", exact: true }).click();
  await guide.waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(await guide.evaluate(el => el.scrollWidth <= el.clientWidth), true);
  await page.waitForTimeout(350);
  await page.screenshot({ path: "work/usage-guide-mobile.png" });
  await guide.getByRole("button", { name: "知道了，先看看" }).click();
  await context.addCookies([{ name: "crous-locale", value: "en", url: origin }]);
  await page.reload();
  await page.getByRole("button", { name: "How to use", exact: true }).click();
  await guide.getByRole("heading", { name: "Your first visit to CROUS Court" }).waitFor();
  assert.equal(await guide.evaluate(el => el.scrollWidth <= el.clientWidth), true);
  await page.waitForTimeout(350);
  await page.screenshot({ path: "work/usage-guide-english.png" });
  const blocked = await browser.newContext();
  await blocked.addInitScript(() => { Object.defineProperty(window, "localStorage", { get() { throw new Error("blocked"); } }); });
  const blockedPage = await blocked.newPage();
  await blockedPage.goto(origin);
  await blockedPage.getByRole("dialog").waitFor();
  await blockedPage.getByRole("button", { name: "关闭使用说明" }).click();
  await blockedPage.getByRole("dialog").waitFor({ state: "hidden" });
  const uploadContext = await browser.newContext();
  const upload = await uploadContext.newPage();
  await upload.goto(origin + "/upload");
  await upload.getByRole("button", { name: "使用说明", exact: true }).waitFor();
  await upload.waitForTimeout(500);
  assert.equal(await upload.getByRole("dialog").count(), 0, "do not interrupt upload");
  assert.deepEqual(errors, []);
  console.log("Usage guide passed: first visit, dismissal, reopen, venue focus, mobile, English, blocked storage, upload exclusion.");
} finally { await browser.close(); }
